"""Rebuild whole North Jubbal source outputs in an isolated local sandbox."""
import csv
import json
import shutil
import subprocess
import sys
from pathlib import Path
from freeze_reviewed_for_audit import sha

P = Path(__file__).resolve().parent
D = P.parents[4]
SANDBOX = D.parent/'tmp/koya-whole/north-whole-regeneration'
STEM = 'whole-reviewed-preview-20260927'


def verify_freeze():
    freeze_path = P/'whole-reviewed-output-freeze-20260927.json'
    freeze = json.loads(freeze_path.read_text())
    accepted = json.loads((P/'root-whole-output-audit-20260927-pass1.json').read_text())
    assert accepted['material_errors'] == 0 and accepted['sample_size'] >= 20
    assert accepted['freeze_sha256'] == sha(freeze_path)
    for filename,digest in freeze['files'].items():
        assert sha(P/filename) == digest,filename
    for filename in [f'{STEM}-report.json','whole-unfrozen-preview-report.json']:
        report = json.loads((P/filename).read_text())
        for relative,digest in report['input_sha256'].items():
            assert sha(P/relative) == digest,relative
    return freeze


def main():
    verify_freeze()
    fake_data = SANDBOX/'data'
    fake_forms = fake_data/'data/other/forms'
    fake_package = fake_forms/'raw_data'/P.name
    fake_package.mkdir(parents=True,exist_ok=True)
    copied = {}
    for path in P.rglob('*'):
        if not path.is_file() or path.suffix not in {'.py','.json','.jsonl','.csv','.tsv','.txt'}:
            continue
        assert path.stat().st_size < 20_000_000,path
        target = fake_package/path.relative_to(P)
        target.parent.mkdir(parents=True,exist_ok=True)
        shutil.copyfile(path,target)
        copied[str(path.relative_to(P))] = sha(path)
    shutil.copyfile(D/'tags.py',fake_data/'tags.py')
    # Reproduce the pinned glossary baseline with its original importer rather
    # than depending on whatever is currently installed in the shared tree.
    command = [sys.executable,str(fake_package/'import_source.py'),'--install']
    result = subprocess.run(command,cwd=fake_data,capture_output=True,text=True)
    assert result.returncode == 0,(result.stdout,result.stderr)
    canonical = fake_forms/'20260925-bailey-north-jubbal.csv'
    with canonical.open(newline='') as stream:
        old = list(csv.reader(stream))
    assert len(old) == 330
    for script in ['prepare_whole_preview.py','prepare_reviewed_preview.py']:
        result = subprocess.run([sys.executable,str(fake_package/script)],cwd=fake_data,capture_output=True,text=True)
        assert result.returncode == 0,(script,result.stdout,result.stderr)
    compared = {}
    for suffix in ['.csv','-audit.jsonl','-profile.txt']:
        filename = STEM+suffix
        assert sha(fake_package/filename) == sha(P/filename),filename
        compared[filename] = sha(fake_package/filename)
    report = dict(status='reviewed whole CSV, audit and profile reproduce byte-identically',
                  freeze_sha256=sha(P/'whole-reviewed-output-freeze-20260927.json'),
                  producer_sha256=sha(Path(__file__)),compared=compared,
                  copied_input_sha256=copied,legacy_baseline_sha256=sha(canonical),
                  canonical_changes=False,compiled_build=False)
    (P/'whole-reviewed-regeneration-validation.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
    print('837 rows, 688 audit units and complete profile regenerated byte-identically.')


if __name__ == '__main__':
    main()
